import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=(file)=>fs.readFileSync(path.join(root,file),'utf8');

const html=read('index.html');
const css=read('jobsystems-os-2026.css');
const js=read('jobsystems-os-2026.js');
const sw=read('sw.js');
const manifest=JSON.parse(read('manifest.json'));

assert.doesNotThrow(()=>new Function(js),'JOBSystems OS runtime must parse as classic JavaScript');
assert.doesNotThrow(()=>new Function(sw),'service worker must parse as classic JavaScript');
assert.match(html,/jobsystems-os-2026\.css\?v=20261015-1/,'OS stylesheet must load after the legacy product styles');
assert.match(html,/jobsystems-os-2026\.js\?v=20261014-1/,'OS runtime must load after the legacy product scripts');
assert.equal(manifest.name,'JOBSystems');
assert.equal(manifest.short_name,'JOBSystems');
assert.equal(manifest.display,'standalone');
assert.equal(manifest.theme_color,'#080B0A');
assert.match(sw,/jobsystems-v60/,'service worker cache must rotate after the ambient-shell release');
assert.match(sw,/jobsystems-os-2026\.css\?v=20261015-1/,'service worker must cache OS CSS');
assert.match(sw,/jobsystems-os-2026\.js\?v=20261014-1/,'service worker must cache OS JS');
assert.match(html,/<header class="topbar">[\s\S]*?<a class="tb-logo"[^>]*aria-label="JOBSystems home"/,'desktop branding must live in the header');
assert.match(html,/<strong>JOBSystems<\/strong>[\s\S]*?<small>Personal Operating System<\/small>/,'header must preserve the full product identity');
assert.doesNotMatch(html,/<nav class="side-panel"[\s\S]*?class="sidebar-brand"/,'desktop branding must not occupy sidebar space');
assert.match(css,/\.tb-logo\{[^}]*position:absolute;left:14px;top:50%;transform:translateY\(-50%\)/,'desktop branding must anchor to the header left edge above the sidebar');
assert.match(css,/\.topbar \.tb-logo\{[^}]*display:flex!important/,'header branding must override the legacy hidden-logo rule');
assert.match(html,/<header class="topbar">[\s\S]*?<button class="desktop-nav-toggle header-sidebar-toggle"/,'the navigation toggle must live in the header beside the product identity');
assert.doesNotMatch(html,/<nav class="side-panel"[\s\S]*?<button class="desktop-nav-toggle/,'the navigation toggle must not float over sidebar content');
assert.match(css,/\.topbar\{[^}]*grid-template-columns:minmax\(0,1fr\) max-content max-content/,'the header must reserve non-overlapping columns for search, context, and controls');
assert.match(css,/#desktopSearchBar>span:first-of-type\{[^}]*white-space:nowrap;overflow:hidden;text-overflow:ellipsis/,'desktop search text must stay on one line');
assert.match(html,/<div class="os-ambient-field" aria-hidden="true"><\/div>/,'the application shell must include its ambient contour layer');
assert.match(css,/\.os-ambient-field\{[^}]*opacity:\.12/,'ambient contours must remain visually subordinate to dashboard content');
assert.match(css,/@media \(prefers-reduced-motion:reduce\),\(hover:none\)/,'ambient motion must stop for reduced-motion and touch users');
assert.match(sw,/\.\/assets\/os-contours\.svg/,'service worker must cache the ambient contour asset');
assert.match(js,/view-projects/,'Projects must be a first-class global view');
assert.match(js,/view-knowledge/,'Knowledge must be a first-class global view');
assert.match(js,/function osRenderFinance\(/,'Finance must render from live JOBSystems data');
assert.doesNotMatch(js,/nav-label">(?:Finance|Knowledge|Reviews?)</,'Finance, Knowledge, and Reviews must stay out of the desktop navigation');
assert.doesNotMatch(js,/<span>(?:Finance|Knowledge|Reviews?)<\/span><\/button>/,'Finance, Knowledge, and Reviews must stay out of the mobile workspace menu');
assert.doesNotMatch(html,/nav-label">Review</,'the legacy sidebar must not flash a Review shortcut before the OS shell loads');
assert.match(js,/osMbnToday/);
assert.match(js,/osMbnTasks/);
assert.match(js,/osMbnCalendar/);
assert.match(js,/osMbnQuickAdd/);
assert.match(js,/osMbnMore/);
assert.match(css,/--os-lime:#A6FF00/,'JOBSystems lime token must be defined');
assert.match(css,/@media\(max-width:768px\)/,'mobile layout must align with the legacy 768px breakpoint');
assert.match(css,/\.app\.nav-collapsed \.side-panel[^}]*display:none!important/,'collapsed desktop navigation must never leak into the mobile shell');
assert.match(css,/env\(safe-area-inset-bottom\)/,'installed iOS PWA must respect the bottom safe area');
assert.doesNotMatch(html,/J\.O\.B Systems/,'visible application shell should use JOBSystems branding');
assert.doesNotMatch(sw,/J\.O\.B Systems/,'notifications should use JOBSystems branding');
assert.doesNotMatch(read('jelix-auto-scheduler.js'),/J\.O\.B Systems/,'install prompts should use JOBSystems branding');
assert.doesNotMatch(read('productivity-command-center.js'),/J\.O\.B Systems/,'calendar sync messaging should use JOBSystems branding');
assert.doesNotMatch(html,/\\n<link|\\n<script/,'final assets must not be separated by literal escaped newline text');
assert.match(html,/jelix-auto-scheduler\.js\?v=20260929-2/,'install prompt changes must use a new asset version');
assert.match(html,/productivity-command-center\.js\?v=20260929-2/,'calendar branding changes must use a new asset version');
assert.doesNotMatch(html,/<script src="https:\/\/cdn\.jsdelivr\.net\/npm\/chart\.js/,'Chart.js must not block initial startup');
assert.doesNotMatch(html,/<script src="(?:agency|faith|life|fitness|health-game)-command-center/,'workspace enhancements must not block initial startup');
assert.match(read('app-prelude.js'),/function ensureViewAssets\(view\)/,'workspace assets must have a shared lazy loader');
assert.match(read('app-part-07.js'),/loadAllFromSupabase\(\{progressive:true\}\)/,'startup must use progressive cloud sync');
assert.match(read('app-part-07.js'),/Store\.notify\(currentView\)/,'startup must render the active view instead of every view');

console.log('PASS: JOBSystems Personal Operating System shell, global views, branding, responsive navigation, and PWA cache checks verified.');
